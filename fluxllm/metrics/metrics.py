"""Prometheus metrics for the engine and API layer.

All engine components report through one :class:`EngineMetrics` instance.
Counters/gauges/histograms use the ``fluxllm_`` prefix so deployments can
scrape a single ``/metrics`` endpoint.
"""

from __future__ import annotations

from typing import TYPE_CHECKING

from prometheus_client import (
    CollectorRegistry,
    Counter,
    Gauge,
    Histogram,
    generate_latest,
)

from fluxllm.engine.request import CompletionReason, RequestTimings

if TYPE_CHECKING:
    from fluxllm.cache.block_manager import BlockManager


class EngineMetrics:
    """Central metric registry. Safe to call from any thread."""

    def __init__(self, registry: CollectorRegistry | None = None) -> None:
        self.registry = registry or CollectorRegistry()

        # -- request lifecycle counters -------------------------------------
        self.requests_received = Counter(
            "fluxllm_requests_received_total",
            "Generation requests accepted by the engine",
            registry=self.registry,
        )
        self.requests_completed = Counter(
            "fluxllm_requests_completed_total",
            "Requests that generated until a natural stop condition",
            registry=self.registry,
        )
        self.requests_cancelled = Counter(
            "fluxllm_requests_cancelled_total",
            "Requests cancelled by clients or engine shutdown",
            registry=self.registry,
        )
        self.requests_failed = Counter(
            "fluxllm_requests_failed_total",
            "Requests that failed during execution",
            registry=self.registry,
        )
        self.preemptions = Counter(
            "fluxllm_scheduler_preemptions_total",
            "Sequences preempted because the KV pool was exhausted",
            registry=self.registry,
        )
        self.scheduler_iterations = Counter(
            "fluxllm_scheduler_iterations_total",
            "Continuous scheduling iterations executed",
            registry=self.registry,
        )
        self.batched_forwards = Counter(
            "fluxllm_batched_model_forwards",
            "Model forwards that executed multiple sequences at once, with "
            "the cumulative sequences-per-forward sum as the counter value",
            registry=self.registry,
        )

        # -- token counters ---------------------------------------------------
        self.prompt_tokens = Counter(
            "fluxllm_prompt_tokens_total",
            "Prompt tokens submitted to the engine",
            registry=self.registry,
        )
        self.generated_tokens = Counter(
            "fluxllm_generated_tokens_total",
            "Output tokens generated by the engine",
            registry=self.registry,
        )

        # -- gauges -------------------------------------------------------------
        self.queue_depth = Gauge(
            "fluxllm_requests_queued",
            "Requests waiting in the scheduler queue",
            registry=self.registry,
        )
        self.running_requests = Gauge(
            "fluxllm_requests_running",
            "Sequences currently admitted (prefill or decode)",
            registry=self.registry,
        )
        self.batch_size = Gauge(
            "fluxllm_scheduler_batch_size",
            "Sequence count in the active batch",
            registry=self.registry,
        )
        self.kv_blocks_used = Gauge(
            "fluxllm_kv_blocks_used",
            "Logical KV blocks currently allocated",
            registry=self.registry,
        )
        self.kv_blocks_free = Gauge(
            "fluxllm_kv_blocks_free",
            "Logical KV blocks free in the pool",
            registry=self.registry,
        )
        self.kv_cache_utilization = Gauge(
            "fluxllm_kv_cache_utilization_ratio",
            "Fraction of the logical KV block pool in use",
            registry=self.registry,
        )
        self.prefix_hits = Counter(
            "fluxllm_prefix_cache_hits_total",
            "Prefix-cache block reuse events observed by the manager",
            registry=self.registry,
        )
        self.prefix_misses = Counter(
            "fluxllm_prefix_cache_misses_total",
            "Blocks allocated fresh while the prefix cache was enabled",
            registry=self.registry,
        )
        self.prefix_reused_tokens = Counter(
            "fluxllm_prefix_cache_reused_tokens_total",
            "Prompt tokens served from pooled block reuse",
            registry=self.registry,
        )
        self.prefix_hit_rate = Gauge(
            "fluxllm_prefix_cache_hit_rate",
            "Fraction of prefix-cache block lookups served from cache",
            registry=self.registry,
        )

        # -- latency histograms ---------------------------------------------------
        self._prefill = Histogram(
            "fluxllm_prefill_latency_seconds",
            "Prefill phase latency (admission to first token)",
            buckets=(0.01, 0.025, 0.05, 0.1, 0.25, 0.5, 1, 2, 5),
            registry=self.registry,
        )
        self._ttft = Histogram(
            "fluxllm_time_to_first_token_seconds",
            "Time from request submission to first streamed token",
            buckets=(0.05, 0.1, 0.25, 0.5, 1, 2, 5, 10, 30, 60),
            registry=self.registry,
        )
        self._inter_token = Histogram(
            "fluxllm_inter_token_latency_seconds",
            "Latency between successive streamed tokens",
            buckets=(0.01, 0.025, 0.05, 0.1, 0.25, 0.5, 1, 2, 5),
            registry=self.registry,
        )
        self._e2e = Histogram(
            "fluxllm_request_latency_seconds",
            "End-to-end request latency (submission to completion)",
            buckets=(0.25, 0.5, 1, 2, 5, 10, 30, 60, 120),
            registry=self.registry,
        )

    # -- events ----------------------------------------------------------------
    def on_submitted(self, num_prompt_tokens: int) -> None:
        self.requests_received.inc()
        self.prompt_tokens.inc(num_prompt_tokens)

    def on_token(self, generated_count: int) -> None:
        self.generated_tokens.inc()

    def on_iteration(self, batch_size: int, block_manager: BlockManager) -> None:
        self.scheduler_iterations.inc()
        self.batch_size.set(batch_size)
        self.running_requests.set(batch_size)
        self.kv_blocks_used.set(block_manager.used_blocks)
        self.kv_blocks_free.set(block_manager.free_blocks)
        self.kv_cache_utilization.set(block_manager.utilization)
        # Gauge only: prefix counters are recorded per allocation event
        # (on_prefix_hit/on_prefix_miss), never from snapshot deltas — a new
        # engine's block manager resets its snapshot while this singleton
        # persists, so deltas would go negative across engines.
        self.prefix_hit_rate.set(
            block_manager.prefix_cache.hit_rate if block_manager.prefix_cache is not None else 0.0
        )

    def on_prefix_hit(self, reused_tokens: int) -> None:
        """One block was shared from the prefix cache (allocation-time event)."""
        self.prefix_hits.inc()
        self.prefix_reused_tokens.inc(reused_tokens)

    def on_prefix_miss(self) -> None:
        """One block was allocated fresh while prefix caching was enabled."""
        self.prefix_misses.inc()

    def set_queue_depth(self, depth: int) -> None:
        self.queue_depth.set(depth)

    def inc_preemptions(self) -> None:
        self.preemptions.inc()

    def on_batched_forward(self, sequence_count: int) -> None:
        """One model forward advanced ``sequence_count`` sequences at once."""
        # Counter value doubles as total batched sequences executed.
        self.batched_forwards.inc(sequence_count)

    # -- latency recording ---------------------------------------------------
    def record_ttft(self, timings: RequestTimings) -> None:
        ttft = timings.ttft
        if ttft is not None:
            self._ttft.observe(ttft)
        prefill = timings.prefill_latency
        if prefill is not None:
            self._prefill.observe(prefill)

    def record_inter_token(self, seconds: float) -> None:
        self._inter_token.observe(seconds)

    def record_completion(self, timings: RequestTimings) -> None:
        total = timings.total_latency
        if total is not None:
            self._e2e.observe(total)
        decode = timings.decode_latency
        if decode is not None and decode > 0:
            pass  # decode span derivable from e2e + ttft; histogram kept simple

    def on_finished(self, request_reason: CompletionReason, timings: RequestTimings) -> None:
        if request_reason is CompletionReason.CANCELLED:
            self.requests_cancelled.inc()
        elif request_reason is CompletionReason.ERROR:
            self.requests_failed.inc()
        else:
            self.requests_completed.inc()
        self.record_completion(timings)

    # -- exposition -----------------------------------------------------------
    def render(self) -> bytes:
        """Prometheus text exposition for the /metrics endpoint."""
        return generate_latest(self.registry)

    def record_prefill_latency(self, seconds: float) -> None:
        self._prefill.observe(seconds)


#: Process-wide metrics singleton used by engine and API unless overridden.
global_metrics = EngineMetrics()
